#Solicite um número inteiro ao usuário e mostre a tabuada de multiplicação desse número de 1 a 5.

numero : int;

numero = int(input("Digite um número para tabuada 1 a 5.\n"))

print(f"Número escolhido: {numero}")
print(f"1 x {numero} = {numero * 1}")
print(f"2 x {numero} = {numero * 2}")
print(f"3 x {numero} = {numero * 3}")
print(f"4 x {numero} = {numero * 4}")
print(f"5 x {numero} = {numero * 5}")


